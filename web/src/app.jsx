/* If anything breaks, never leave a blank screen in an emergency app. */
class ErrorBoundary extends React.Component {
  constructor(p) { super(p); this.state = { error: null }; }
  static getDerivedStateFromError(error) { return { error }; }
  componentDidCatch(error) { try { console.error(error); } catch (e) { /* ignore */ } }
  render() {
    if (!this.state.error) return this.props.children;
    return (
      <div className="cshell" style={{ paddingTop: 40 }}>
        <h1 style={{ fontSize: 22 }}>Something went wrong</h1>
        <p style={{ color: "var(--text-dim)", fontWeight: 600 }}>ക്ഷമിക്കണം, ആപ്പിൽ ഒരു പ്രശ്നം ഉണ്ടായി. Reload the app. If you need help now, call 112.</p>
        <button className="btn btn-lg btn-block btn-primary" onClick={() => location.reload()}>Reload</button>
        <a className="btn btn-lg btn-block btn-danger" href="tel:112">Call 112</a>
      </div>
    );
  }
}

ReactDOM.createRoot(document.getElementById("root")).render(<ErrorBoundary><AppProvider><AppBody /></AppProvider></ErrorBoundary>);

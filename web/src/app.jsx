function project(lat, lng) {
  const x = (lng - KERALA_PROJ.minLng) * KERALA_PROJ.cosMean * KERALA_PROJ.scale + KERALA_PROJ.pad;
  const y = (KERALA_PROJ.maxLat - lat) * KERALA_PROJ.scale + KERALA_PROJ.pad;
  return [x, y];
}
function unproject(x, y) {
  const lng = (x - KERALA_PROJ.pad) / (KERALA_PROJ.cosMean * KERALA_PROJ.scale) + KERALA_PROJ.minLng;
  const lat = KERALA_PROJ.maxLat - (y - KERALA_PROJ.pad) / KERALA_PROJ.scale;
  return [lat, lng];
}
function nearestDistrict(lat, lng) {
  const [x, y] = project(lat, lng);
  let best = null, bestD = Infinity;
  for (const d of KERALA_DISTRICTS) {
    const dd = Math.hypot(d.cx - x, d.cy - y);
    if (dd < bestD) { bestD = dd; best = d; }
  }
  return best;
}
function districtCenterLatLng(id) {
  const d = districtById[id];
  return unproject(d.cx, d.cy);
}


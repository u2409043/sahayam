// Density clustering of open requests (same idea as the backend's DBSCAN: eps 1.5 km, min 3)
function computeHotspots(reqs, epsKm = 1.5, minPts = 3) {
  const pts = reqs.filter(r => r.status !== "Resolved" && r.lat != null && r.lng != null);
  const label = new Array(pts.length).fill(undefined);
  const near = (i) => pts.map((p, j) => j).filter(j => kmBetween(pts[i].lat, pts[i].lng, pts[j].lat, pts[j].lng) <= epsKm);
  let c = 0;
  for (let i = 0; i < pts.length; i++) {
    if (label[i] !== undefined) continue;
    const n = near(i);
    if (n.length < minPts) { label[i] = -1; continue; }
    label[i] = c; const queue = [...n];
    while (queue.length) {
      const j = queue.shift();
      if (label[j] === -1) label[j] = c;
      if (label[j] !== undefined) continue;
      label[j] = c;
      const nj = near(j);
      if (nj.length >= minPts) queue.push(...nj);
    }
    c++;
  }
  const out = [];
  for (let k = 0; k < c; k++) {
    const members = pts.filter((_, i) => label[i] === k);
    const lat = members.reduce((s, m) => s + m.lat, 0) / members.length;
    const lng = members.reduce((s, m) => s + m.lng, 0) / members.length;
    const radius = Math.max(600, ...members.map(m => kmBetween(lat, lng, m.lat, m.lng) * 1000 + 400));
    out.push({ lat, lng, radius, count: members.length });
  }
  return out;
}



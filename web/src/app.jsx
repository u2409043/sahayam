function classifyUrgency(text, flags) {
  const t = (text || "").toLowerCase();
  let score = 32;
  if (CRITICAL_KEYWORDS.some(k => t.includes(k))) score = 90;
  else if (HIGH_KEYWORDS.some(k => t.includes(k))) score = 66;
  if (flags.elderly) score += 9;
  if (flags.children) score += 9;
  if (flags.medical) score += 14;
  if (flags.people >= 5) score += 6;
  score = Math.min(100, Math.round(score));
  const priority = score >= 80 ? "Emergency" : score >= 55 ? "High" : score >= 30 ? "Medium" : "Low";
  return { score, priority };
}


function TaskCard({ req, me }) {
  const { tick, network, updateStatus, resolveWithOutcome } = useApp();
  const [smsNote, setSmsNote] = useState("");
  const [picking, setPicking] = useState(false);
  const lastAt = req.history && req.history.length ? req.history[req.history.length - 1].at : req.createdAt;
  const idleLeft = CLAIM_TIMEOUT_MIN - (tick - lastAt) / 60000;
  const d = districtById[req.districtId];
  const km = kmBetween(me.lat, me.lng, req.lat, req.lng);
  const idx = STATUS_FLOW.indexOf(req.status);
  const next = NEXT_ACTION[req.status];
  const offline = network === "offline";

  const act = () => {
    if (next.to === "Resolved") { setPicking(true); return; }
    updateStatus(req.id, next.to); buzz(20);
    setSmsNote(offline ? `SHM1 UPD ${req.id} ${next.code}` : "");
  };
  const finishWith = (o) => {
    resolveWithOutcome(req.id, o, me.name); buzz(20); setPicking(false);
    setSmsNote(offline ? `SHM1 UPD ${req.id} DONE ${o.toUpperCase()}` : "");
  };

  return (
    <div className="task-card" style={{ borderLeftColor: req.status === "Resolved" ? "var(--low)" : PRI_COLOR[req.priority] }}>
      <div className="task-top">
        <div style={{ flex: 1, minWidth: 0 }}>
          <div className="task-title">{req.name || (req.sos ? "SOS caller" : "Caller")}</div>
          <div className="task-loc"><IconMapPin size={12} style={{ verticalAlign: "-1px" }} /> {d.name} · {km.toFixed(1)} km · {relTime(req.createdAt, tick)}</div>
        </div>
        <span className="pri-pill" style={{ background: PRI_BG[req.priority], color: PRI_COLOR[req.priority] }}>{req.priority}</span>
      </div>
      <div className="task-desc">{req.desc}</div>
      <div className="chips" style={{ gap: 6 }}>
        {req.channel === "sms" && <span className="badge sms"><IconMessage size={11} /> SMS{req.approxLocation ? " · approx. location" : ""}</span>}
        {req.people > 1 && <span className="badge media"><IconUsers size={11} /> {req.people} people</span>}
      </div>
      <MediaPlayer media={req.media} pending={req.mediaPending} />
      <div>
        <div className="progress">{STATUS_FLOW.map((s, i) => <i key={s} className={i <= idx ? "on" : ""} />)}</div>
        <div className="progress-labels" style={{ marginTop: 4 }}>{STATUS_FLOW.map(s => <span key={s}>{s}</span>)}</div>
      </div>
      {req.status === "Resolved" ? (
        <span className="status-pill" style={{ background: "var(--low-bg)", color: "var(--low)", alignSelf: "flex-start" }}><IconCheck size={11} style={{ verticalAlign: "-1px" }} /> Resolved{req.outcome ? " · " + (OUTCOMES.find(o => o.id === req.outcome) || {}).label : ""}</span>
      ) : (
        <>
          {req.status === "Assigned" && idleLeft > 0 && (
            <div className="warn-note">Tap “I'm on my way” within {Math.ceil(idleLeft)} min, or this request goes back to the pool for another volunteer.</div>
          )}
          {(req.flags || []).some(f => f !== "dup") && <div className="warn-note">Unverified request. Call the caller before travelling far.</div>}
          {picking ? <OutcomePicker onPick={finishWith} onCancel={() => setPicking(false)} /> : next && (
            <button className="btn btn-lg btn-block btn-primary" onClick={act}>
              {next.to === "Resolved" ? <IconCheckCircle size={20} /> : <IconNavigation size={18} />} {next.label}{offline ? " (by SMS)" : ""}
            </button>
          )}
          <div className="task-actions">
            <a className="btn btn-ghost" href={req.phone ? "tel:+91" + req.phone : undefined} aria-disabled={!req.phone}
               style={!req.phone ? { opacity: .45, pointerEvents: "none" } : null}><IconPhone size={16} /> Call</a>
            <a className="btn btn-ghost" target="_blank" rel="noopener"
               href={`https://www.google.com/maps/dir/?api=1&destination=${req.lat},${req.lng}`}><IconMap size={16} /> Directions</a>
          </div>
          {req.phone && <div className="phone-line mono">+91 {req.phone}</div>}
        </>
      )}
      {smsNote && <div className="sms-note">Status update queued as SMS to the control room:<code className="mono">{smsNote}</code></div>}
    </div>
  );
}


function ForecastPanel() {
  const { conditions, risk, scenario, applyScenario, setCondition, alerts, issueAlert, subscriptions, tick, setSelectedDistrictId } = useApp();
  const [target, setTarget] = useState(null);
  const [level, setLevel] = useState("Warning");
  const [en, setEn] = useState("");
  const [ml, setMl] = useState("");
  const [sent, setSent] = useState("");
  const rows = [...KERALA_DISTRICTS].sort((a, b) => risk[b.id].score - risk[a.id].score);

  const compose = (id) => {
    const lv = risk[id].tier === "Low" ? "Watch" : risk[id].tier;
    const tpl = alertTemplate(id, lv);
    setTarget(id); setLevel(lv); setEn(tpl.en); setMl(tpl.ml); setSent("");
    setSelectedDistrictId(id);
  };
  const changeLevel = (lv) => { setLevel(lv); const tpl = alertTemplate(target, lv); setEn(tpl.en); setMl(tpl.ml); };
  const send = () => {
    const dName = districtById[target].name;
    Promise.resolve(issueAlert({ districtId: target, level, en, ml })).then(n => {
      setSent(`${level} issued for ${dName}. It shows in the app for that district and went by SMS to ${n} subscriber${n === 1 ? "" : "s"}.`);
      setTarget(null);
    }).catch(() => {});
  };

  return (
    <div className="card">
      <div className="card-head">
        <IconShield size={16} /><h3>Flood risk outlook and alerts</h3>
        <span className="sub">next 48 hours · past disasters + rain warnings + dam levels</span>
      </div>
      <div className="card-body" style={{ display: "flex", flexDirection: "column", gap: 12 }}>
        <div className="sample-row">
          {SCENARIO_IDS.map(id => (
            <button key={id} className={"btn btn-sm " + (scenario === id ? "btn-primary" : "btn-ghost")} onClick={() => applyScenario(id)}>{SCENARIOS[id].label}</button>
          ))}
          {scenario === "custom" && <span className="badge review">Custom inputs</span>}
        </div>
        <span className="hint">
          {scenario !== "custom" ? SCENARIOS[scenario].note + ". " : ""}
          Demo inputs. In production the IMD district warnings, rainfall totals and KSEB dam levels are fetched automatically; edit any cell to see the score update.
          Score = 30% past disasters + 30% IMD warning + 25% 72-hour rain + 15% upstream dam (districts without a major dam split that weight between rain and warning).
        </span>

        <div className="table-wrap">
          <table className="risk-table">
            <thead><tr><th>District</th><th>IMD warning</th><th>Rain, 72 h</th><th>Upstream dam</th><th>Past</th><th>Risk</th><th></th></tr></thead>
            <tbody>
              {rows.map(dd => {
                const r = risk[dd.id];
                const dam = DAMS.find(x => x.districts[0] === dd.id) || DAMS.find(x => x.districts.includes(dd.id));
                const live = alerts.find(a => a.districtId === dd.id && tick - a.at < ALERT_TTL);
                return (
                  <tr key={dd.id} className={target === dd.id ? "on" : ""}>
                    <td><button className="link-btn" style={{ padding: 0, fontSize: 13.5, textAlign: "left" }} onClick={() => setSelectedDistrictId(dd.id)}>{dd.name}</button></td>
                    <td>
                      <select className="sev-select" value={conditions.imd[dd.id]} onChange={e => setCondition("imd", dd.id, e.target.value)} style={{ color: IMD_HEX[conditions.imd[dd.id]] }} aria-label={dd.name + " IMD warning"}>
                        {IMD_LEVELS.map(l => <option key={l} value={l}>{l}</option>)}
                      </select>
                    </td>
                    <td><input className="num-in" type="number" min="0" max="800" value={conditions.rain[dd.id]} onChange={e => setCondition("rain", dd.id, Math.max(0, +e.target.value || 0))} aria-label={dd.name + " rain in mm"} /> mm</td>
                    <td>{dam ? (<><input className="num-in" type="number" min="0" max="100" value={conditions.dams[dam.id]} onChange={e => setCondition("dams", dam.id, Math.min(100, Math.max(0, +e.target.value || 0)))} aria-label={dam.name + " level percent"} />% <span className="hint">{dam.name}</span></>) : <span className="hint">none</span>}</td>
                    <td className="mono">{r.events.map(e => e.year).join(", ") || "–"}</td>
                    <td style={{ minWidth: 150 }}>
                      <div className="risk-cell">
                        <span className="rbar"><i style={{ width: Math.round(r.score * 100) + "%", background: TIER_HEX[r.tier] }} /></span>
                        <span className="pri-pill" style={{ background: TIER_BG[r.tier], color: TIER_HEX[r.tier] }}>{r.tier}</span>
                      </div>
                    </td>
                    <td>{live ? <span className="badge sms">Alert live</span> : <button className="btn btn-ghost btn-sm" onClick={() => compose(dd.id)}>Alert</button>}</td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>

        {target && (
          <div className="compose">
            <div className="row" style={{ display: "flex", gap: 10, alignItems: "center", flexWrap: "wrap" }}>
              <b style={{ fontSize: 15 }}>New alert · {districtById[target].name}</b>
              <div className="tabs" style={{ flex: "1 1 280px" }}>
                {["Watch", "Warning", "Severe"].map(l => <button key={l} className={level === l ? "on" : ""} onClick={() => changeLevel(l)}>{l}</button>)}
              </div>
            </div>
            <div className="field" style={{ margin: 0 }}><label htmlFor="al-en">English message</label><textarea id="al-en" rows="3" value={en} onChange={e => setEn(e.target.value)} /></div>
            <div className="field" style={{ margin: 0 }}><label htmlFor="al-ml">Malayalam message</label><textarea id="al-ml" rows="3" lang="ml" value={ml} onChange={e => setMl(e.target.value)} /></div>
            <span className="hint">Goes to everyone who set {districtById[target].name} as their area in the app, and by SMS to {subscriptions.filter(x => x.district === target).length} subscriber(s). Always review the text before sending.</span>
            <div style={{ display: "flex", gap: 8 }}>
              <button className="btn btn-danger" onClick={send}><IconSend size={15} /> Issue alert</button>
              <button className="btn btn-ghost" onClick={() => setTarget(null)}>Cancel</button>
            </div>
          </div>
        )}
        {sent && <div className="toast" role="status">{sent}</div>}

        <span className="section-label">Alerts issued</span>
        <div className="sms-log">
          {alerts.map(a => (
            <div key={a.id} className="sms-log-row" style={{ borderLeft: `4px solid ${TIER_HEX[a.level]}` }}>
              <div className="top">
                <b style={{ color: TIER_HEX[a.level] }}>{a.level}</b><span>· {districtById[a.districtId].name}</span><span>· {relTime(a.at, tick)}</span><span>· SMS to {a.sentTo}</span>
                {tick - a.at >= ALERT_TTL && <span className="badge" style={{ background: "var(--surface-3)", color: "var(--text-dim)" }}>Expired</span>}
              </div>
              <code>{a.en}</code>
            </div>
          ))}
        </div>
      </div>
    </div>
  );
}


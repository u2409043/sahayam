/* Optional one-time-code check. Never required to send a request. */
function OtpSheet({ phone, onClose, onDone }) {
  const { t, lang } = useApp();
  const [code, setCode] = useState(null);
  const [entry, setEntry] = useState("");
  const [err, setErr] = useState("");
  const { otpSend, otpVerify } = useApp();
  const [busy, setBusy] = useState(false);
  const [sentOnce, setSentOnce] = useState(false);
  const send = () => {
    setBusy(true); setErr("");
    otpSend(phone).then(r => { setCode(r.demoCode || null); setSentOnce(true); setEntry(""); })
      .catch(e => setErr(e.message)).finally(() => setBusy(false));
  };
  const check = () => {
    setBusy(true);
    otpVerify(phone, entry, code).then(() => onDone()).catch(e => setErr(e.message)).finally(() => setBusy(false));
  };
  return (
    <div className="overlay" role="dialog" aria-modal="true" aria-label={t.otpTitle} lang={lang}>
      <div className="sheet-backdrop" onClick={onClose} />
      <div className="sheet">
        <div className="sheet-grab" />
        <div className="sheet-head"><h2>{t.otpTitle}</h2><button className="back-btn" onClick={onClose} aria-label={t.otpSkip}><IconX size={20} /></button></div>
        <div className="sheet-body">
          <span className="hint" style={{ fontSize: 14 }}>{t.verifyWhy}</span>
          {!sentOnce ? (
            <>
              <button className="btn btn-lg btn-block btn-primary" disabled={busy} onClick={send}><IconMessage size={18} /> {t.otpSend} · +91 {phone}</button>
              {err && <div className="err-note" role="alert">{err}</div>}
            </>
          ) : (
            <>
              <span style={{ fontWeight: 700 }}>{t.otpSent(phone)}</span>
              {code && <div className="warn-note">{t.otpDemo(code)}</div>}
              <label className="section-label" htmlFor="otp-in">{t.otpEnter}</label>
              <input id="otp-in" className="input otp-in" inputMode="numeric" autoComplete="one-time-code" maxLength={4}
                     value={entry} onChange={e => { setEntry(e.target.value.replace(/\D/g, "").slice(0, 4)); setErr(""); }} />
              {err && <div className="err-note" role="alert">{err}</div>}
              <button className="btn btn-lg btn-block btn-primary" disabled={entry.length !== 4 || busy} onClick={check}>{t.otpVerify}</button>
              <button className="link-btn" onClick={send}>{t.otpResend}</button>
            </>
          )}
        </div>
        <div className="sheet-foot"><button className="btn btn-block btn-ghost" onClick={onClose}>{t.otpSkip}</button></div>
      </div>
    </div>
  );
}


function parseSms(body) {
  const raw = (body || "").trim();
  let m = raw.match(/^SHM1\s+(SOS|RES|MED|FOD|SHL|OTH)\s+(-?\d{1,2}(?:\.\d+)?),(-?\d{1,3}(?:\.\d+)?)(?:\s+P(\d+))?(?:\s+F([ECM]+))?\s*(.*)$/i);
  if (m) {
    const code = m[1].toUpperCase(), lat = +m[2], lng = +m[3], f = (m[5] || "").toUpperCase();
    const located = inKerala(lat, lng);
    return {
      ok: true, format: "app", sos: code === "SOS", category: CODE_CAT[code], lat, lng, located,
      people: m[4] ? +m[4] : 1, flags: { elderly: f.includes("E"), children: f.includes("C"), medical: f.includes("M") },
      text: m[6] || "", place: located ? districtOf(lat, lng).name : null,
    };
  }
  m = raw.match(/^(HELP|SOS|SAHAYAM)\b[\s,:.-]*(.*)$/i);
  if (m) {
    const rest = m[2] || "", low = rest.toLowerCase();
    const place = [...PLACE_INDEX].sort((a, b) => b.name.length - a.name.length).find(p => new RegExp("\\b" + p.name.toLowerCase() + "\\b").test(low));
    const cat = /medic|insulin|dialysis|doctor|hospital|pregnan|labou?r|injur|bleed/.test(low) ? "medical"
      : /food|water|milk|hungry|drink/.test(low) ? "food"
      : /shelter|camp|evacuat|house damaged/.test(low) ? "shelter" : "rescue";
    const pm = low.match(/(\d+)\s*(people|persons|members|of us|family|children|kids)/) || low.match(/family of\s*(\d+)/);
    return {
      ok: true, format: "keyword", sos: m[1].toUpperCase() === "SOS", category: cat,
      lat: place ? place.lat : null, lng: place ? place.lng : null, located: !!place, place: place ? place.name : null,
      people: pm ? +pm[1] : 1, text: rest,
      flags: { elderly: /elder|old|grand|aged|amma|appooppan|ammoomma/.test(low), children: /child|kid|baby|infant/.test(low), medical: /sick|medic|insulin|dialysis|pregnan|wheelchair|bedridden|oxygen/.test(low) },
    };
  }
  return { ok: false, error: "Not a Sahayam message" };
}


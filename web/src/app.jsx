/* Risk index, next 48 h. A transparent weighted score so every rating can be explained to the
   public. In the backend this is the slot for a trained model (e.g. gradient boosting on IMD
   rainfall, CWC river gauges and mapped 2018 flood extents). */
function computeRisk(cond) {
  const out = {};
  KERALA_DISTRICTS.forEach(d => {
    const dams = DAMS.filter(x => x.districts.includes(d.id));
    const top = dams.map(x => ({ dam: x, pct: cond.dams[x.id] ?? 0 })).sort((a, b) => b.pct - a.pct)[0] || null;
    const f = {
      hist: HIST_EXPOSURE[d.id],
      imd: IMD_SCORE[cond.imd[d.id] || "Green"],
      rain: Math.min(1, (cond.rain[d.id] || 0) / 350),
      dam: top ? Math.max(0, (top.pct - 75) / 25) : null,
    };
    const w = f.dam == null ? { hist: 0.30, imd: 0.35, rain: 0.35, dam: 0 } : { hist: 0.30, imd: 0.30, rain: 0.25, dam: 0.15 };
    const score = w.hist * f.hist + w.imd * f.imd + w.rain * f.rain + w.dam * (f.dam || 0);
    const tier = score >= 0.75 ? "Severe" : score >= 0.55 ? "Warning" : score >= 0.35 ? "Watch" : "Low";
    out[d.id] = { score, tier, f, w, dam: top, imdLevel: cond.imd[d.id] || "Green", rainMm: cond.rain[d.id] || 0,
      events: HISTORY_EVENTS.filter(e => e.districts[d.id]) };
  });
  return out;
}


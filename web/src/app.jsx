function pathToRings(dstr) {
  const rings = []; let cur = null; const re = /([MLZ])\s*(?:([\d.]+),([\d.]+))?/g; let m;
  while ((m = re.exec(dstr))) {
    if (m[1] === "M") { cur = []; rings.push(cur); }
    if (m[1] !== "Z" && m[2] && cur) cur.push(unproject(+m[2], +m[3]));
  }
  return rings.filter(r => r.length > 2);
}
function boundsOf(rings) {
  let a = 90, b = 180, c = -90, d = -180;
  rings.forEach(r => r.forEach(([la, ln]) => { a = Math.min(a, la); b = Math.min(b, ln); c = Math.max(c, la); d = Math.max(d, ln); }));
  return [[a, b], [c, d]];
}

async function api(path, { method = "GET", body, form, timeout = 15000 } = {}) {
  const ctl = typeof AbortController !== "undefined" ? new AbortController() : null;
  const tm = ctl ? setTimeout(() => ctl.abort(), timeout) : null;
  const headers = { "X-Device-Id": getDeviceId() };
  if (AUTH_TOKEN) headers.Authorization = "Bearer " + AUTH_TOKEN;
  let payload;
  if (form) payload = form;
  else if (body !== undefined) { headers["Content-Type"] = "application/json"; payload = JSON.stringify(body); }
  try {
    const res = await fetch(apiUrl(path), { method, headers, body: payload, signal: ctl ? ctl.signal : undefined });
    const text = await res.text();
    let data = null; try { data = text ? JSON.parse(text) : null; } catch (e) { /* not JSON */ }
    if (!res.ok) { const err = new Error((data && data.detail && (typeof data.detail === "string" ? data.detail : "Please check the details and try again.")) || `The server returned an error (${res.status}).`); err.status = res.status; throw err; }
    if (data === null && text) { const err = new Error("Not a Sahayam server."); err.status = 0; throw err; }
    return data;
  } catch (e) {
    if (e.name === "AbortError") { const err = new Error("The server took too long to answer."); err.network = true; throw err; }
    if (e.status == null) { e.network = true; e.message = "Can't reach the Sahayam server."; }
    throw e;
  } finally { if (tm) clearTimeout(tm); }
}

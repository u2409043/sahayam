function histHex(x) {
  // pale teal-grey (never hit) to deep blue (hit repeatedly)
  const a = [230, 238, 240], b = [31, 92, 138];
  return "rgb(" + a.map((v, i) => Math.round(v + (b[i] - v) * x)).join(",") + ")";
}


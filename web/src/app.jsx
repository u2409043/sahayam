function encodeSms({ category, lat, lng, people, flags = {}, text = "", sos = false }) {
  const code = sos ? "SOS" : (CAT_CODE[category] || "OTH");
  const f = (flags.elderly ? "E" : "") + (flags.children ? "C" : "") + (flags.medical ? "M" : "");
  let s = `SHM1 ${code} ${lat.toFixed(4)},${lng.toFixed(4)} P${Math.max(1, people || 1)}${f ? " F" + f : ""}`;
  const clean = text.replace(/\s+/g, " ").replace(/[^\x20-\x7E]/g, "").trim();
  if (clean) s += " " + clean;
  return s.slice(0, 160);
}


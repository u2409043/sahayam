function RequestForm({ category, mediaFirst, onBack, onSent }) {
  const { t, lang, network, addRequest, addMyReportId, ingestSms, myArea, setMyArea } = useApp();
  const [geo, requestGeo] = useGeolocation();
  const [loc, setLoc] = useState(() => {
    const last = loadLocal("sahayam_last_loc", null);
    return last ? { ...last, source: "last" } : null;
  });
  const [mapOpen, setMapOpen] = useState(false);
  const [sits, setSits] = useState([]);
  const [people, setPeople] = useState(1);
  const [vuln, setVuln] = useState([]);
  const [details, setDetails] = useState("");
  const [phone, setPhone] = useState(() => loadLocal("sahayam_phone", ""));
  const [media, setMedia] = useState(null);
  const [smsDraft, setSmsDraft] = useState(null);
  const [sending, setSending] = useState(false);
  const [sendErr, setSendErr] = useState("");
  const offline = network === "offline";

  useEffect(() => { requestGeo(); }, [requestGeo]);
  useEffect(() => { if (geo.state === "found") setLoc({ lat: geo.lat, lng: geo.lng, source: "gps" }); }, [geo]);

  const toggle = (arr, setArr, id) => setArr(arr.includes(id) ? arr.filter(x => x !== id) : [...arr, id]);
  const cat = CATEGORIES.find(c => c.id === category);
  const situations = SITUATIONS[category] || [];

  const build = () => {
    const vulnItems = VULNERABLE.filter(v => vuln.includes(v.id));
    const flags = { elderly: vuln.includes("elderly"), children: vuln.includes("children"), medical: vulnItems.some(v => v.flag === "medical"), people };
    const sitText = situations.filter(s => sits.includes(s.id)).map(s => s.en);
    const parts = [...sitText, people > 1 ? `${people >= 10 ? "10+" : people} people` : null, ...vulnItems.filter(v => v.desc).map(v => v.desc), details.trim() || null].filter(Boolean);
    let desc = parts.length ? parts.join(". ") + "." : "";
    if (media) desc = (desc ? desc + " " : "") + (media.kind === "video" ? "Video message attached." : "Voice message attached.");
    if (!desc) desc = `${STR.en["cat_" + category]} help needed.`;
    return { flags, desc, smsText: [...sitText, details.trim()].filter(Boolean).join(". ") || (media ? `${media.kind} message pending upload` : "") };
  };

  const finish = (req) => {
    if (phone) saveLocal("sahayam_phone", phone);
    saveLocal("sahayam_last_loc", { lat: loc.lat, lng: loc.lng });
    if (!myArea) setMyArea(districtOf(loc.lat, loc.lng).id);
    addMyReportId(req.id);
    buzz([30, 40, 30]);
    onSent(req.id, !!req.mergedFrom);
  };

  const submit = () => {
    if (!loc || sending) { if (!loc) setMapOpen(true); return; }
    const { flags, desc, smsText } = build();
    const toSms = () => setSmsDraft({ body: encodeSms({ category, lat: loc.lat, lng: loc.lng, people, flags, text: smsText }), desc, flags });
    if (offline) { toSms(); return; }
    const tri = classifyUrgency(desc, flags);
    setSendErr(""); setSending(true);
    Promise.resolve(addRequest({
      name: null, phone: phone || null, desc, category, priority: tri.priority, mlScore: tri.score, people,
      has_elderly: flags.elderly, has_children: flags.children, has_medical: flags.medical,
      lat: loc.lat, lng: loc.lng, media, needsReview: !!media && sits.length === 0 && !details.trim(),
      deviceId: getDeviceId(), userText: sits.length ? null : details.trim(),
      gps: geo.state === "found" ? { lat: geo.lat, lng: geo.lng } : null,
    })).then(req => { setSending(false); finish(req); })
      .catch(e => { setSending(false); if (e.network) toSms(); else setSendErr(e.message); });
  };

  const confirmSms = () => {
    Promise.resolve(ingestSms(smsDraft.body, phone ? "+91 " + phone : null, { fromCitizen: true,
      desc: smsDraft.desc, phone: phone || null, media, mediaPending: !!media,
      needsReview: !!media && sits.length === 0 && !details.trim(), approxLocation: false,
      deviceId: getDeviceId(), userText: sits.length ? null : details.trim(),
      gps: geo.state === "found" ? { lat: geo.lat, lng: geo.lng } : null,
    })).then(res => { setSmsDraft(null); if (res && res.ok) finish(res.req); }).catch(e => { setSmsDraft(null); setSendErr(e.message); });
  };

  const mediaBlock = (
    <div className="block">
      <div className="block-title"><h2>{t.cantType}</h2><small>{t.optional}</small></div>
      <span className="hint" style={{ marginTop: -6 }}>{t.cantTypeSub}</span>
      <MediaCapture media={media} onChange={setMedia} t={t} offline={offline} />
    </div>
  );

  return (
    <>
      <div className="cshell has-dock" lang={lang}>
        <div className="screen-head">
          <button className="back-btn" onClick={onBack} aria-label={t.back}><IconArrowLeft size={20} /></button>
          {mediaFirst
            ? <span className="cat-icon" style={{ background: "var(--accent-tint)", color: "var(--accent)", width: 40, height: 40 }}><IconVideo size={22} /></span>
            : cat && <span className="cat-icon" style={{ background: cat.bg, color: cat.color, width: 40, height: 40 }}><cat.Icon size={22} /></span>}
          <h1>{mediaFirst ? t.videoTile : t["cat_" + category]}</h1>
        </div>

        <div className="block">
          <div className="block-title"><h2>{t.location}</h2></div>
          <LocationCard loc={loc} geo={geo} onOpenMap={() => setMapOpen(true)} t={t} />
        </div>

        {mediaFirst && mediaBlock}

        {!mediaFirst && (
          <div className="block">
            <div className="block-title"><h2>{t.whatsHappening}</h2><small>{t.tapAll}</small></div>
            <div className="chips">
              {situations.map(s => (
                <Chip key={s.id} on={sits.includes(s.id)} warn onClick={() => toggle(sits, setSits, s.id)}>{lang === "ml" ? s.ml : s.en}</Chip>
              ))}
            </div>
          </div>
        )}

        {!mediaFirst && mediaBlock}

        <div className="block">
          <div className="block-title"><h2>{t.whoNeeds}</h2></div>
          <PeopleStepper value={people} onChange={setPeople} label={t.people} />
          <span className="hint" style={{ marginTop: 4 }}>{t.anyVuln}</span>
          <div className="chips">
            {VULNERABLE.map(v => (
              <Chip key={v.id} on={vuln.includes(v.id)} onClick={() => toggle(vuln, setVuln, v.id)}>{lang === "ml" ? v.ml : v.en}</Chip>
            ))}
          </div>
        </div>

        <div className="block">
          <div className="block-title"><h2><label htmlFor="c-details">{t.details}</label></h2><small>{t.optional}</small></div>
          <textarea id="c-details" className="input" rows="2" value={details} onChange={e => setDetails(e.target.value)} placeholder={t.detailsPh} />
        </div>

        <PhoneInput id="c-phone" value={phone} onChange={setPhone} t={t} />
        <p className="hint legal-note">{t.falseAlarm}</p>
      </div>

      <div className="dock" lang={lang}>
        <div className="dock-inner">
          {!loc && <div className="dock-note">{t.sendNeedLoc}</div>}
          {sendErr && <div className="dock-note" role="alert">{sendErr} {t.call112Hint}</div>}
          <button className="btn btn-lg btn-block btn-danger" onClick={submit} disabled={sending} aria-busy={sending}>
            {!loc ? <IconMapPin size={20} /> : offline ? <IconMessage size={20} /> : <IconSend size={20} />}
            {" "}{!loc ? t.setOnMap : offline ? t.sendSms : t.send}
          </button>
        </div>
      </div>

      {mapOpen && <MapSheet initial={loc} onClose={() => setMapOpen(false)} onConfirm={(l) => { setLoc(l); setMapOpen(false); }} />}
      {smsDraft && <SmsSheet body={smsDraft.body} onClose={() => setSmsDraft(null)} onSent={confirmSms} />}
    </>
  );
}


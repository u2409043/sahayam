function useGeolocation() {
  const [geo, setGeo] = useState({ state: "idle" });
  const request = useCallback(() => {
    if (!("geolocation" in navigator)) { setGeo({ state: "unavailable" }); return; }
    setGeo({ state: "locating" });
    let settled = false;
    const done = (v) => { if (!settled) { settled = true; setGeo(v); } };
    const timer = setTimeout(() => done({ state: "unavailable" }), 9000);
    try {
      navigator.geolocation.getCurrentPosition(
        (p) => {
          clearTimeout(timer);
          const { latitude: lat, longitude: lng, accuracy } = p.coords;
          done(inKerala(lat, lng) ? { state: "found", lat, lng, accuracy } : { state: "outside" });
        },
        () => { clearTimeout(timer); done({ state: "unavailable" }); },
        { enableHighAccuracy: true, timeout: 8000, maximumAge: 60000 }
      );
    } catch (e) { clearTimeout(timer); done({ state: "unavailable" }); }
  }, []);
  return [geo, request];
}


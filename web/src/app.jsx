function PriorityQueue() {
  const { requests, selectedDistrictId } = useApp();
  const [filter, setFilter] = useState("open");
  const isFlagged = (r) => r.status !== "Resolved" && (r.flags || []).length > 0;
  const counts = useMemo(() => ({
    flagged: requests.filter(r => isFlagged(r) && (!selectedDistrictId || r.districtId === selectedDistrictId)).length,
  }), [requests, selectedDistrictId]);
  const filtered = useMemo(() => {
    let rs = requests;
    if (selectedDistrictId) rs = rs.filter(r => r.districtId === selectedDistrictId);
    if (filter === "open") rs = rs.filter(r => r.status !== "Resolved" && !(r.flags || []).includes("blocked"));
    if (filter === "review") rs = rs.filter(r => r.needsReview && r.status !== "Resolved");
    if (filter === "flagged") rs = rs.filter(isFlagged);
    return [...rs].sort((a, b) => ((a.status === "Resolved") - (b.status === "Resolved")) || (PRI_RANK[a.priority] - PRI_RANK[b.priority]) || (a.createdAt - b.createdAt));
  }, [requests, selectedDistrictId, filter]);

  return (
    <div className="card">
      <div className="card-head">
        <IconLayers size={16} /><h3>Request queue</h3>
        <span className="sub">{selectedDistrictId ? districtById[selectedDistrictId].name + " · " : ""}{filtered.length} shown</span>
      </div>
      <div className="card-body" style={{ display: "flex", flexDirection: "column", gap: 10 }}>
        <div className="tabs">
          {[["open", "Open"], ["flagged", `Flagged${counts.flagged ? " · " + counts.flagged : ""}`], ["review", "Needs review"], ["all", "All"]].map(([k, l]) => (
            <button key={k} className={filter === k ? "on" : ""} onClick={() => setFilter(k)}>{l}</button>
          ))}
        </div>
        {filter === "flagged" && <span className="hint">Flagged requests stay in the queue. Check them, then verify, merge or dismiss. Blocked numbers only appear here.</span>}
        {filtered.length === 0 ? (
          <div className="empty-state"><IconCheckCircle size={28} /><p>Nothing here right now.</p></div>
        ) : (
          <div className="queue-list">{filtered.map(r => <QueueRow key={r.id} r={r} />)}</div>
        )}
      </div>
    </div>
  );
}

